const categories = [...new Set(questionBank.map((question) => question.category))];

function getRandomCategories(count = 3) {
  return [...categories]
    .sort(() => Math.random() - 0.5)
    .slice(0, Math.max(0, count));
}

function getQuestionByCategory(category, excludedQuestionIds = []) {
  const availableQuestions = questionBank.filter(
    (question) => question.category === category && !excludedQuestionIds.includes(question.id),
  );
  const questions = availableQuestions.length
    ? availableQuestions
    : questionBank.filter((question) => question.category === category);
  if (questions.length === 0) return null;
  return questions[Math.floor(Math.random() * questions.length)];
}

